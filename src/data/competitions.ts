export function categoryInfo(id: Category) {
  return categories.find((category) => category.id === id)!;
}

export function filterCompetitions(query: string, category: string, level: string) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return competitions.filter((competition) => {
    const text = [competition.name, competition.description, ...competition.keywords].join(' ').toLocaleLowerCase();
    return terms.every((term) => text.includes(term))
      && (category === 'all' || competition.category === category)
      && (level === 'all' || competition.levels.includes(level as Level));
  });
}
